  statNames[value]?.[lang === 'de' ? 0 : 1] ?? value;
export const statValue = (stat: string, value: number) =>
  ['maxHp', 'hp', 'maxResource', 'resource', 'armor'].includes(stat) ||
  (['damage', 'healing'].includes(stat) && Math.abs(value) >= 1)
    ? `${value >= 0 ? '+' : ''}${Number(value.toFixed(1))}`
    : `${value >= 0 ? '+' : ''}${Math.round(value * 100)}%`;
export const rarityName = (rarity: number, lang: Lang) =>
  (lang === 'de'
    ? ['Gewöhnlich', 'Ungewöhnlich', 'Selten', 'Episch', 'Legendär', 'Einzigartig']
    : ['Common', 'Uncommon', 'Rare', 'Epic', 'Legendary', 'Unique'])[
    Math.max(0, Math.min(5, rarity))
  ];
export const dateText = (date: number, lang: Lang) =>
  new Intl.DateTimeFormat(lang === 'de' ? 'de-DE' : 'en-GB', {
    dateStyle: 'medium',
    timeStyle: 'short',
  }).format(date);
